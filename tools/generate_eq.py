"""Generate Q28 RBJ biquads, following https://www.w3.org/TR/audio-eq-cookbook/.
No coefficient design, float or trig runs in the firmware PCM callback.
"""
from pathlib import Path
import math,sys
RATES=(8000,16000,32000,44100,48000,96000)
# HP Hz, bass-center Hz / dB, high shelf Hz / dB, fixed preamp dB.
PRESETS=((60,220,1.5,3500,-1.5,-.5),(70,200,3,3200,-3,-1),(80,180,4.5,3000,-4.5,-2))
def design(kind,fs,hz,db=0):
 w=2*math.pi*hz/fs;c=math.cos(w);sn=math.sin(w);A=10**(db/40)
 if kind=='hp':
  alpha=sn/(2*math.sqrt(.5));b=((1+c)/2,-(1+c),(1+c)/2);a=(1+alpha,-2*c,1-alpha)
 elif kind=='peak':
  alpha=sn/(2*.8);b=(1+alpha*A,-2*c,1-alpha*A);a=(1+alpha/A,-2*c,1-alpha/A)
 else:
  alpha=sn/math.sqrt(2);v=2*math.sqrt(A)*alpha
  b=(A*((A+1)+(A-1)*c+v),-2*A*((A-1)+(A+1)*c),A*((A+1)+(A-1)*c-v))
  a=((A+1)-(A-1)*c+v,2*((A-1)-(A+1)*c),(A+1)-(A-1)*c-v)
 return tuple(round(x/a[0]*(1<<28)) for x in (*b,a[1],a[2]))
lines=['// Generated by tools/generate_eq.py; coefficients ordered b0,b1,b2,a1,a2.', '#pragma once','#include <cstdint>','namespace vinyl {', 'struct TonePreset { int32_t biquad[3][5]; int32_t preampQ15; };', 'constexpr unsigned EQ_RATES[] = {'+','.join(map(str,RATES))+'};','constexpr TonePreset EQ_PRESETS[][3] = {']
for fs in RATES:
 lines.append('  { // '+str(fs)+' Hz')
 for hp,center,bass,treble,cut,preamp in PRESETS:
  coeffs=(design('hp',fs,hp),design('peak',fs,center,bass),design('shelf',fs,treble,cut))
  lines.append('    {{{'+ '},{'.join(','.join(map(str,c)) for c in coeffs)+'}},'+str(round(10**(preamp/20)*32768))+'},')
 lines.append('  },')
lines+=['};','}']
path=Path(__file__).resolve().parents[1]/'shared/eq_coefficients.h';result='\n'.join(lines)+'\n'
if '--check' in sys.argv: assert path.read_text()==result, 'EQ coefficient table differs from generator'
else: path.write_text(result)
